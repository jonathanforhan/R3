#pragma once

#include <vector>
#include <vulkan/vulkan.h>
#include "engine/api/Types.hpp"

namespace R3 {

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// PBR
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

struct R3_API PBRVertexUniformBufferObject {
    alignas(16) fmat4 view;
    alignas(16) fmat4 projection;
    alignas(16) fmat4 lightViewProjection;
};

struct R3_API PBRPushConstants {
    fmat4 model;
    fvec3 viewPosition;
    uint32 numLights;
    uint32 iAlbedo;
    uint32 iMetallicRoughness;
    uint32 iNormal;
    uint32 iAmbientOcclusion;
    uint32 iEmissive;
    uint32 bSelected;
};

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// Editor
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

struct R3_API EditorVertexUniformBufferObject {
    alignas(16) fmat4 view;
    alignas(16) fmat4 projection;
};

struct R3_API EditorPushConstants {
    fmat4 model;
    uint32 entityID;
};

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// Cubemap
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

struct R3_API CubemapPushConstants {
    uint32 iCubemap;
};

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// Shadow
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

struct R3_API ShadowPushConstants {
    fmat4 model;
    fmat4 lightViewProj;
};

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// Generic
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

struct R3_API PointLightShaderObject {
    alignas(16) fvec3 position;
    alignas(16) fvec3 color;
    alignas(4) float intensity;
};

/// Vertex used by shaders
struct R3_API Vertex {
    fvec3 position;
    fvec3 normal;
    fvec2 textureCoords;
    ivec4 boneIDs;
    fvec4 weights;
};

} // namespace R3
